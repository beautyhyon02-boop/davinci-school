/** 옛 한국사·세계사 세트도 사회 예시를 받는다(사회 통합 과목, 대표 2026-09-30). */
const ALIAS: Record<string, string> = { '한국사': '사회', '세계사': '사회', '역사': '사회' }

/** 과목별 참조 단원 구조 요약 블록(3단계 생성 프롬프트용). 모르는 과목이면 ''. */
export function referenceUnitBlock(subject: string): string {
  const u = UNITS[ALIAS[subject] ?? subject]
  if (!u) return ''
  return [
    `참고 — 공개 예시 단원의 구조(과목: ${ALIAS[subject] ?? subject}). 구조만 참고하고 문장·자료는 쓰지 않는다; 우리 세트는 이보다 한 단계 높은 사고(관찰 → 추론 → 종합)를 요구한다.`,
    `[${u.title}]`,
    ...u.lines.map((l, i) => `${i + 1}. ${l}`),
    REFERENCE_SOURCE_LINE,
  ].join('\n')
}

/** 2단계(재구성)용 짧은 꼴: 제목 + 첫 줄(재구조화 논리)만. */
export function referenceUnitShort(subject: string): string {
  const u = UNITS[ALIAS[subject] ?? subject]
  if (!u) return ''
  return `참고 — 공개 예시 단원의 재구조화(과목: ${ALIAS[subject] ?? subject}, 구조만 참고): [${u.title}] ${u.lines[0]} ${REFERENCE_SOURCE_LINE}`
}

